# 호환하기 위함 — 단어/독해 등 다른 영역은 이 3단계 체계를 그대로 쓰고 있어 건드리지 않는다).
CEFR_TO_LEGACY_LEVEL: dict[str, str] = {
    "A1": "beginner",
    "A2": "beginner",
    "B1": "intermediate",
    "B2": "intermediate",
    "C1": "advanced",
    "C2": "advanced",
}


def _topic(cefr_level: str, name: str, description: str, parts: list[tuple[str, str]], is_exam_focus: bool = False) -> TopicDef:
    return TopicDef(
        cefr_level=cefr_level,
        name=name,
        description=description,
        is_exam_focus=is_exam_focus,
        parts=[PartDef(pname, pdesc) for pname, pdesc in parts],
    )


